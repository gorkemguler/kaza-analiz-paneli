// EGM bültenlerinde kısaltılmış yazılan iller
const ALIASES = { 'D.BAKIR': 'DİYARBAKIR' }

const byUpper = new Map(ILLER.map((il) => [il.ad.toLocaleUpperCase('tr-TR'), il]))

export function findIl(egmName) {
  const key = egmName.trim().toLocaleUpperCase('tr-TR')
  return byUpper.get(ALIASES[key] ?? key)
}
